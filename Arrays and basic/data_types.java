public class data_types {
    public static void main(String[] args) {
        // primetive datatypes
        int rollno = 25;
        char oneletter = 'g';
        float decimal = 3.14f;
        double longedecimal_value = 325648.45634;
        long longest_integer = 7993951101L;
        boolean tORf = true;
        // non primetive datatypes
        String name = "mohdghouse";
        System.out.println(rollno);
        System.out.println(oneletter);
        System.out.println(decimal);
        System.out.println(longedecimal_value);
        System.out.println(longest_integer);
        System.out.println(tORf);
        System.out.println(name);

    }
}